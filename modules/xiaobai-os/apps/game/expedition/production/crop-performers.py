"""Pack authored layers without downscaling; preserve stage coordinates and gesture pivots."""
import argparse
import json
from pathlib import Path
from PIL import Image

parser = argparse.ArgumentParser()
parser.add_argument('source', type=Path)
parser.add_argument('assets', type=Path)
parser.add_argument('manifest', type=Path)
args = parser.parse_args()
if args.source.resolve() == args.assets.resolve():
    raise ValueError('Keep original padded artwork separate from packed assets')
imports, entries = [], []
before_pixels = after_pixels = before_bytes = after_bytes = 0
for index, path in enumerate(sorted(args.source.glob('*.webp'))):
    image = Image.open(path).convert('RGBA')
    if image.size != (420, 495):
        raise ValueError(f'{path}: expected authored 420x495 stage')
    bounds = image.getchannel('A').getbbox()
    if not bounds:
        raise ValueError(f'{path}: empty layer')
    # One transparent pixel preserves filtering at the cut edge when rotated/scaled.
    x, y, right, bottom = bounds
    x, y, right, bottom = max(0, x - 1), max(0, y - 1), min(420, right + 1), min(495, bottom + 1)
    cropped = image.crop((x, y, right, bottom))
    target = args.assets / path.name
    cropped.save(target, format='WEBP', quality=100, method=6, exact=True)
    imports.append(f"import layer{index} from '../assets/performance/{path.name}?url&no-inline';")
    entries.append(f"    '{path.stem}': {{ src: layer{index}, x: {x}, y: {y}, width: {right-x}, height: {bottom-y} }},")
    before_pixels += image.width * image.height
    after_pixels += cropped.width * cropped.height
    before_bytes += path.stat().st_size
    after_bytes += target.stat().st_size
args.manifest.write_text('// Generated by production/crop-performers.py; coordinates are on the original stage.\n'
    + '\n'.join(imports) + '\nexport const ACTOR_STAGE = { width: 420, height: 495 } as const;\n'
    + 'export const SPRITES = {\n' + '\n'.join(entries) + '\n} as const;\n', encoding='utf-8')
print(json.dumps(dict(layers=len(entries), beforePixels=before_pixels, afterPixels=after_pixels,
                     beforeBytes=before_bytes, afterBytes=after_bytes)))
