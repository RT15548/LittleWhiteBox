import { build } from 'esbuild';
import { outputRoot } from './build/output-root.mjs';
import { stagedInputs } from './build/staged-inputs.mjs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const plugin = resolve(root, 'server-plugin/littlewhitebox-server');
const manifest = JSON.parse(await readFile(resolve(plugin, 'manifest.json'), 'utf8'));
const banner = '// Generated by scripts/build-server-plugin.mjs from the server manifest.\n';
const outputs = new Map([
    [resolve(outputRoot, 'shared/server-plugin/identity.js'), `${banner}export const SERVER_PLUGIN_ID = ${JSON.stringify(manifest.id)};\nexport const SERVER_PLUGIN_NAME = ${JSON.stringify(manifest.name)};\nexport const SERVER_PLUGIN_VERSION = ${JSON.stringify(manifest.version)};\nexport const SERVER_PLUGIN_BASE = \`/api/plugins/\${SERVER_PLUGIN_ID}\`;\n`],
    [resolve(outputRoot, 'server-plugin/littlewhitebox-server/package.json'), JSON.stringify({ name: manifest.id, type: 'commonjs', main: 'index.js',
        description: manifest.description, private: true, engines: { node: '>=18.0.0' } }, null, 4) + '\n'],
]);
// Identity is generated first because the shared web error copy imports it.
for (const [path, content] of outputs) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
}
const runtime = resolve(outputRoot, 'server-plugin/littlewhitebox-server/web/web-runtime.cjs');
const result = await build({ absWorkingDir: root, entryPoints: ['modules/agent-core/web/server-entry.js'],
    bundle: true, platform: 'node', format: 'cjs', target: 'node18', outfile: runtime,
    write: false, minify: true, legalComments: 'none', tsconfigRaw: {}, plugins: [stagedInputs] });
const content = result.outputFiles[0].text;
await mkdir(dirname(runtime), { recursive: true });
await writeFile(runtime, content);
console.log('Built server identity and web runtime.');
