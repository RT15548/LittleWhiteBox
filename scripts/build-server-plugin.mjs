import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const plugin = resolve(root, 'server-plugin/littlewhitebox-server');
const manifest = JSON.parse(await readFile(resolve(plugin, 'manifest.json'), 'utf8'));
const check = process.argv.includes('--check');
const banner = '// Generated by scripts/build-server-plugin.mjs from the server manifest.\n';
const outputs = new Map([
    [resolve(root, 'shared/server-plugin/identity.js'), `${banner}export const SERVER_PLUGIN_ID = ${JSON.stringify(manifest.id)};\nexport const SERVER_PLUGIN_NAME = ${JSON.stringify(manifest.name)};\nexport const SERVER_PLUGIN_VERSION = ${JSON.stringify(manifest.version)};\nexport const SERVER_PLUGIN_BASE = \`/api/plugins/\${SERVER_PLUGIN_ID}\`;\n`],
    [resolve(plugin, 'package.json'), JSON.stringify({ name: manifest.id, type: 'commonjs', main: 'index.js',
        description: manifest.description, private: true, engines: { node: '>=18.0.0' } }, null, 4) + '\n'],
]);
// Identity is generated first because the shared web error copy imports it.
for (const [path, content] of outputs) {
    if (check) {
        if (await readFile(path, 'utf8') !== content) throw new Error(`Stale server artifact: ${path}`);
    } else {
        await mkdir(dirname(path), { recursive: true });
        await writeFile(path, content);
    }
}
const runtime = resolve(plugin, 'web/web-runtime.cjs');
const result = await build({ absWorkingDir: root, entryPoints: ['modules/agent-core/web/server-entry.js'],
    bundle: true, platform: 'node', format: 'cjs', target: 'node18', outfile: runtime,
    write: false, minify: true, legalComments: 'none', tsconfigRaw: {} });
const content = result.outputFiles[0].text;
if (check) {
    if (await readFile(runtime, 'utf8') !== content) throw new Error(`Stale server artifact: ${runtime}`);
} else {
    await mkdir(dirname(runtime), { recursive: true });
    await writeFile(runtime, content);
}
console.log(check ? 'Server identity and web runtime are current.' : 'Built server identity and web runtime.');
